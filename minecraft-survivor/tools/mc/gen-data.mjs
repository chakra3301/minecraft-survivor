// Writes the game's generated data from the roster and the rendered sprites:
//   js/data/mobdex.js       G.DEX / G.DEX_BY / G.getPokemon (engine names kept on purpose), G.ARMOUR
//   js/data/sprites-meta.js G.SPRITE_META (from assets/mobs/{key}/meta.json)
//   node tools/mc/gen-data.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { ROSTER, SKIN_MOBS, dexRecord, ARMOUR_GAME } from './roster.mjs';

const game = path.join(path.dirname(fileURLToPath(import.meta.url)), '../..');
const head = s => `/* ============ ${s} — GENERATED by tools/mc/gen-data.mjs from tools/mc/roster.mjs; do not edit ============ */\n`;

const rows = ROSTER.map(dexRecord);
await writeFile(path.join(game, 'js/data/mobdex.js'), head('mobdex.js') +
  '// Engine names are PokéSurvivor\'s: G.DEX is the Mobdex, `dex` is the mob id, `key` its asset folder.\n' +
  'G.DEX = [\n' + rows.map(r => '  ' + JSON.stringify(r)).join(',\n') + '\n];\n' +
  'G.DEX_BY = {};\nfor (const p of G.DEX) G.DEX_BY[p.dex] = p;\nG.getPokemon = dex => G.DEX_BY[dex];\n' +
  '// Armour tiers (`arm` above): stat multipliers, run spawn chance, bonus emeralds, book chance, knockback immunity.\n' +
  'G.ARMOUR = ' + JSON.stringify(ARMOUR_GAME) + ';\n');

const meta = {};
let missing = 0;
for (const m of [...ROSTER, ...SKIN_MOBS]) {
  try { meta[m.skinOf ? m.key : m.dex] = JSON.parse(await readFile(path.join(game, 'assets/mobs', m.key, 'meta.json'), 'utf8')); }
  catch { missing++; console.warn('not rendered yet:', m.key); }
}
await writeFile(path.join(game, 'js/data/sprites-meta.js'), head('sprites-meta.js') +
  '// Same schema as PokéSurvivor: s shadow size, a anims {w,h frame; n frames; r rows (8 directions);\n' +
  '// d per-frame duration in 1/60 s; ax,ay ground anchor}, sh Enchanted sheets in s/, hv hovers.\n' +
  'G.SPRITE_META = {\n' + Object.entries(meta).map(([k, v]) => `  ${/^\d+$/.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n') + '\n};\n');
console.log(`${rows.length} mobs (${rows.filter(r => !r.v).length} base, ${rows.filter(r => r.v).length} variants), ${missing} without sprites`);
