// Fills the generated blocks of firestore.rules:
//   <admins>        the moderators: the online config's "admins" (or --admins uid1,uid2)
//   <achievements>  each achievement's reward in Spawner pulls, so the server knows how many keys
//                   and emeralds a new achievement may give and rejects invented ones
//                   (ported from PokéSurvivor's tools/make_rules.js)
//   node make-rules.mjs [--config ../online.config.json] [--admins uid,uid] [--out firestore.rules]
// Deploy afterwards: npx firebase deploy --only firestore:rules,firestore:indexes,database --project <id>
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { loadGame } from '../tools/web/game-data.mjs';
import { readConfig, DEFAULT_CONFIG } from '../tools/web/online-config.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = k => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
const src = path.join(here, 'firestore.rules');
const out = path.resolve(opt('--out') || src);

let admins;
if (opt('--admins') != null) admins = opt('--admins').split(',').map(s => s.trim()).filter(Boolean);
else admins = (await readConfig(opt('--config') || DEFAULT_CONFIG, { emulator: true })).online.admins;
for (const u of admins) if (!/^[A-Za-z0-9_-]{6,128}$/.test(u)) throw new Error(`"${u}" isn't a Firebase uid`);

const G = await loadGame();
const L = G.AchDefs.LIST;
if (!L.every(a => /^[A-Za-z0-9_-]+$/.test(a.id))) throw new Error('odd achievement id');
// Value of an achievement's reward in pulls (Trial Key = 1, Ominous Key = 10, 300 emeralds = 1).
// Every achievement may give up to 1 Trial Key on its own (counted apart, by number of achievements).
const val = r => Math.max(0, ((r || {}).t1 || 0) - 1) + 10 * ((r || {}).t10 || 0) + ((r || {}).coins || 0) / 300;
// Grouped by value: one set operation per group (one by one went past the 1,000-operation cap).
const groups = {};
for (const a of L) { const v = +val(a.reward).toFixed(3); if (v > 0) (groups[v] = groups[v] || []).push(a.id); }
const terms = Object.entries(groups).map(([v, list]) => `${v} * a.intersection([${list.map(i => `'${i}'`).join(', ')}].toSet()).size()`);

let rules = await readFile(src, 'utf8');
const block = (name, body) => {
  const re = new RegExp(`    // <${name}>[\\s\\S]*?// </${name}>`);
  if (!re.test(rules)) throw new Error(`firestore.rules: the <${name}> markers are missing`);
  rules = rules.replace(re, () => body);
};
block('admins', [
  '    // <admins> (generated by make-rules.mjs from the online config\'s "admins")',
  `    function admin() { return signedIn() && me() in [${admins.map(u => `'${u}'`).join(', ')}]; }`,
  '    // </admins>'].join('\n'));
block('achievements', [
  '    // <achievements> (generated by make-rules.mjs, don\'t edit by hand)',
  "    function achNew() { return request.resource.data.save.get('ach', {}).diff(resource.data.save.get('ach', {})).addedKeys(); }",
  // The diff is built once (let) and most saves add no achievement: then nothing else is evaluated
  // (rules have a 1,000-expression cap per request).
  `    function achV() { let a = achNew(); return a.size() == 0 ? 0 : (${terms.length ? terms.join('\n        + ') : '0'}); }`,
  '    // </achievements>'].join('\n'));
await writeFile(out, rules);
console.log(`${path.relative(process.cwd(), out)}: ${admins.length} moderator(s), ${L.length} achievements (${terms.length} reward groups)`);
